        /// <summary>
        /// 打包握手控制指令，带有CRC验证码
        /// </summary>
        /// <param name="ip">本地地址</param>
        /// <param name="port">本地端口号</param>
        /// <returns>返回字节数组</returns>
        public static byte[] PackBytesHandShake(string ip, int port)
        {
            string cmd = string.Format("$ZepTools handshake request,{0}:{1},{2:X2}%", ip, port, 0x00);
            byte[] res = Encoding.UTF8.GetBytes(cmd);
            UInt16 crc = Data_GetCRC16(res, res.Length - 3);
            res[res.Length - 3] = (byte)((crc & 0xFF00) >> 8);
            res[res.Length - 2] = (byte)(crc & 0xFF);

            return res;
        }

