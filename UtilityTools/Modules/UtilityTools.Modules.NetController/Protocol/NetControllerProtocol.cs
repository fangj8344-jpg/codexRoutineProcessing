        /// <summary>
        /// CRC计算，参数模型：x16+x15+x2+1；宽度：16；多项式：0x8005；初始值：0xFFFF
        /// </summary>
        /// <param name="ucDataBuffer"></param>
        /// <param name="usDataLen"></param>
        /// <returns></returns>
        public static UInt16 Data_GetCRC16(byte[] ucDataBuffer, int usDataLen)
        {
            byte uchCRCHi = 0xFF;               //高CRC 字节初始化

            byte uchCRCLo = 0xFF;               //低CRC 字节初始化

            int uIndex;                       //CRC 循环中的索引

            for (int i = 0; i < usDataLen; ++i)
            {
                uIndex = uchCRCHi ^ ucDataBuffer[i];
                uchCRCHi = (byte)(uchCRCLo ^ auchCRCHi[uIndex]);
                uchCRCLo = auchCRCLo[uIndex];
            }

            return (UInt16)(uchCRCLo << 8 | uchCRCHi);                // 高低字节翻转
        }

        /// <summary>
        /// 检查回包内容，包括格式内容以及CRC校验
        /// </summary>
        /// <param name="response">回包数据</param>
        /// <param name="length">数据长度</param>
        /// <returns>是否是合规的回包响应</returns>
        public static bool CheckResponse(byte[] response, int length)
        {
            if (response == null)
                return false;
            if (response[0] != '$' || response[length - 1] != '%')
            {
                return false;
            }

            return true;
        }

        /// <summary>
        /// 检查回包是否是来自虚拟设备的回复报文
        /// </summary>
        /// <param name="response">回包数据</param>
        /// <param name="length">数据长度</param>
        /// <returns>是否是虚拟设备的回包响应</returns>
        public static bool CheckIsVirtualDevice(byte[] response, int length)
        {
            string ret = Encoding.Default.GetString(response, 0, length);
            return string.Equals(ret, "VirtualDevice");
        }

        /// <summary>
        /// 解析回包中的错误指令类型
        /// </summary>
        /// <param name="errCode">错误类型</param>
        /// <returns>回包是否有错误</returns>
        /// <exception cref="Exception">错误异常</exception>
        public static bool ParseErrCode(int errCode)
        {
            switch (errCode)
            {
                case 0x00:
                    return true;
                case 0x01:
                    throw new Exception("非法参数");
                case 0x02:
                    throw new Exception("执行失败");
                case 0x03:
                    throw new Exception("CRC校验失败");
                case 0xE0:
                    throw new Exception("系统错误");
                case 0xE1:
                    throw new Exception("高压错误");
                case 0xE2:
                    throw new Exception("灯丝损耗");
                case 0xE3:
                    throw new Exception("高压启动失败");
                case 0x71:
                    throw new Exception("高压未开启");
                case 0x72:
                    throw new Exception("开枪中不可清除错误");
                case 0x73:
                    throw new Exception("当前未开枪");
                case 0x74:
                    throw new Exception("开枪状态下不可切换灯丝种类");
                case 0x75:
                    throw new Exception("错误未清除");
                default:
                    throw new Exception(string.Format("返回未知错误代码：0x{0:X}", errCode));
            }
        }
